function getTranslation(key, lang) {
  const selectedLang = lang || localStorage.getItem('legalai_language') || 'en';
  if (UI_TRANSLATIONS[selectedLang] && UI_TRANSLATIONS[selectedLang][key]) {
    return UI_TRANSLATIONS[selectedLang][key];
  }
  return UI_TRANSLATIONS['en'][key] || key;
}

function applyLocalTranslations(lang) {
  const selectedLang = lang || localStorage.getItem('legalai_language') || 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const txt = getTranslation(key, selectedLang);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.hasAttribute('placeholder')) {
        el.setAttribute('placeholder', txt);
      } else {
        el.value = txt;
      }
    } else {
      // Preserve inner icons if present
      const icon = el.querySelector('i, svg');
      if (icon) {
        el.innerHTML = '';
        el.appendChild(icon);
        el.appendChild(document.createTextNode(' ' + txt));
      } else {
        el.textContent = txt;
      }
    }
  });
}
